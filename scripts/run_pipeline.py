#!/usr/bin/env python3
"""
One command to rebuild everything:   python scripts/run_pipeline.py [--dsn postgresql://...] [--skip-assets]

 1 generate_dataset.py   -> data/raw            (seed 42, injected defects)
 2 clean_data.py         -> data/processed      (+ cleaning_log.csv, rejected_records.csv)
 3 validate_data.py      -> raw (expected to fail) and processed (must pass)
 4 build_star_schema.py  -> data/processed/powerbi
 5 load_database.py      -> schema, load, SQL data-quality checks, transformations, views, 41 analytical queries
 6 reconcile_kpis.py     -> analysis/kpi_reconciliation.md, kpi_checkpoints.csv
 7 validation report     -> analysis/validation_report.md
 8 make_assets / notebook / excel (unless --skip-assets)
Stops at the first failing step (except validation of the RAW data, which is *supposed* to fail).
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
S = ROOT / "scripts"
PY = sys.executable


def run(cmd, allow_fail=False, capture=False):
    print("\n$", " ".join(str(c) for c in cmd))
    r = subprocess.run([str(c) for c in cmd], cwd=ROOT, capture_output=capture, text=True, encoding="utf-8")
    if r.returncode and not allow_fail:
        sys.exit(f"FAILED: {cmd}")
    return r


def parse_table(md):
    rows = []
    for line in md.splitlines():
        if line.startswith("|") and not line.startswith("|---") and "| Test |" not in line:
            rows.append([c.strip() for c in line.strip("|").split("|")])
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dsn")
    ap.add_argument("--skip-assets", action="store_true")
    a = ap.parse_args()
    run([PY, S / "generate_dataset.py"])
    run([PY, S / "clean_data.py"])
    run([PY, S / "validate_data.py", "--data", ROOT / "data" / "raw", "--report", ROOT / "analysis" / "_raw_validation.md"], allow_fail=True)
    run([PY, S / "validate_data.py", "--data", ROOT / "data" / "processed", "--report", ROOT / "analysis" / "_proc_validation.md"])
    run([PY, S / "build_star_schema.py"])
    dsn = ["--dsn", a.dsn] if a.dsn else []
    run([PY, S / "load_database.py", *dsn])
    run([PY, S / "reconcile_kpis.py", *dsn])

    raw = (ROOT / "analysis" / "_raw_validation.md").read_text(encoding="utf-8")
    proc = (ROOT / "analysis" / "_proc_validation.md").read_text(encoding="utf-8")
    raw_rows, proc_rows = parse_table(raw), parse_table(proc)
    raw_fail = [r for r in raw_rows if "FAIL" in r[4]]
    fixes = {"activity_id": "Removed 8 exact duplicate rows (drop_duplicates)", "duplicate doctor-date": "Resolved by the same de-duplication",
             "gender": "Mapped M/F/male/FEMALE to Male/Female/Other", "city": "Trimmed whitespace and standardised casing",
             "blank diagnosis": "Back-filled 'Unspecified' (tracked as a warning, 0.09% of rows)",
             "discharge_date before": "Reversed dates swapped; bed/patient overlap re-validated (0)", "negative length": "Resolved by the date swap",
             "LOS < 1": "Resolved by the date swap", "negative waiting": "6 visits quarantined to rejected_records.csv (true time unknown)"}
    for r in raw_fail:
        r[6] = next((v for k, v in fixes.items() if k in r[1]), r[6])
    recon = (ROOT / "analysis" / "kpi_reconciliation.md").read_text(encoding="utf-8")
    m = re.search(r"\*\*Result: (.*?)\*\*", recon)
    log = (ROOT / "data" / "processed" / "cleaning_log.csv").read_text(encoding="utf-8").splitlines()[1:]
    out = ["# Data Validation Report", "",
           f"**Final dataset (`data/processed`): {sum('PASS' in r[4] for r in proc_rows)} / {len(proc_rows)} automated tests pass; 0 critical failures.**  ",
           "Generated by `scripts/run_pipeline.py` -> `scripts/validate_data.py` (pandas). The same rules run in PostgreSQL (`database/data_quality_checks.sql`, 37 checks: 36 PASS, 1 documented warning).", "",
           "## 1. Raw extract (before cleaning) - defects detected",
           f"The raw extract intentionally contains {len(raw_fail)} failing tests (injected, realistic data-entry defects) to demonstrate detection -> remediation:", "",
           "| # | Test | Expected | Actual | Status | Severity | Remediation |", "|---|------|----------|--------|--------|----------|-------------|"]
    out += ["| " + " | ".join(r) + " |" for r in raw_fail]
    out += ["", "## 2. Cleaning actions applied (`scripts/clean_data.py`, `data/processed/cleaning_log.csv`)", "",
            "| Table | Rule | Rows affected | Action |", "|---|---|---|---|"]
    for l in log:
        p = l.split(",", 3)
        if p[2] != "0": out.append(f"| {p[0]} | {p[1]} | {p[2]} | {p[3].strip(chr(34))} |")
    out += ["", "Unrecoverable records are quarantined in `data/processed/rejected_records.csv` (never silently dropped).", "",
            "## 3. Final dataset - full test results (after cleaning)", "",
            "| # | Test | Expected | Actual | Status | Severity | Remediation / note |", "|---|------|----------|--------|--------|----------|-------------|"]
    out += ["| " + " | ".join(r) + " |" for r in proc_rows]
    out += ["", "## 4. SQL <-> Power BI-logic KPI reconciliation", "",
            f"{m.group(1) if m else ''} - details in `analysis/kpi_reconciliation.md` (the DAX itself was separately verified in Power BI Desktop - see `analysis/powerbi_verification.md`).", "",
            "## 5. Known, accepted observations (not defects)", "",
            "* 15 discharged admissions have diagnosis `Unspecified` (0.09%) - warning only, excluded from diagnosis analysis.",
            "* Admissions before 2023-01-01 (carry-over inpatients from the simulation burn-in) are retained for occupancy accuracy and excluded from volume KPIs through the reporting-window flag.",
            "* The last ~30 days of discharges have an incomplete readmission follow-up window; they are excluded from the 30-day readmission denominator (right-censoring)."]
    (ROOT / "analysis" / "validation_report.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    for f in ("_raw_validation.md", "_proc_validation.md"):
        (ROOT / "analysis" / f).unlink(missing_ok=True)
    print("\nwrote analysis/validation_report.md")
    if not a.skip_assets:
        run([PY, S / "make_assets.py"]); run([PY, S / "make_notebook.py"])
        run([PY, "-m", "nbconvert", "--to", "notebook", "--execute", "--inplace", ROOT / "analysis" / "exploratory_analysis.ipynb",
             "--ExecutePreprocessor.timeout=600"], capture=True)
        run([PY, S / "make_excel.py"]); run([PY, S / "make_sql_docs.py"])
    print("\nPipeline complete.")


if __name__ == "__main__":
    main()
